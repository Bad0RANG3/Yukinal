/**
 * Agent 输出文本的 Markdown 解析：把模型写回来的文本拆成「块 + 行内」结构，
 * 交给 `components/MarkdownText.tsx` 变成 React 元素。
 *
 * 为什么自己写而不是引一个库：
 *
 * 1. 需要的是「一段对话正文」的子集 —— 标题、列表、围栏代码、引用、表格、
 *    行内代码与强调。完整实现还要带上 HTML 透传、脚注、引用式链接、URL 归一化，
 *    体积和攻击面都远超这里需要的东西；仓库约定也是不为小功能引大依赖。
 * 2. 这条路径上流的是**不可信文本**（模型输出）。这里只产出数据结构，渲染层只创建
 *    我们自己写的元素，没有任何 `dangerouslySetInnerHTML`，因此「写一段 HTML 就能
 *    改变界面」这条路根本不存在 —— 而不是靠过滤得够好。
 *
 * 支持的语法（其余一律按纯文本处理，绝不猜）：
 *   ATX 标题 `#`…`######` 与 setext 标题（`===` / `---` 下划线，但下划线单独出现时按分隔线）；
 *   `-` `*` `+` 与 `1.` `1)` 列表（可嵌套、可 `[x]` 勾选）；围栏代码块 ``` 与 ~~~
 *   （**未闭合时把剩下的都当代码** —— 流式输出里它一定闭不上）与四空格缩进代码块；
 *   引用 `>`；表格（含 `:---:` 对齐）；分隔线；段落；引用式链接；
 *   行内：`code`、**粗**、*斜*、~~删除~~、[链接](url)、裸 URL、图片、数字字符引用（`&#35;`）。
 *   段落整段解析，所以代码段与强调可以跨软换行。
 *
 * 刻意不支持：
 *   - HTML（内联与块级都是普通文字，见上）。
 *   - 图片不会去下载，只显示替代文字：渲染层不该替用户向陌生主机发请求。
 *   - **命名**实体引用（`&copy;`、`&quot;` 按字面显示）：要一张 2231 条的 HTML5 名字表，
 *     几十 KB 纯数据不值得为此引进仓库；数字引用（`&#35;`、`&#x22;`）照常解码。
 *
 * 对照的规范版本固定为 **CommonMark 0.31.2**：实测的差距清单（哪些节全对、哪些节还在丢字）
 * 在 `docs/boundaries/markdown.md`，测量本身是 `tests/markdown-spec.test.ts` 里的 opt-in 用例。
 *
 * 实现分成三个模块，这个文件只负责把它们拼成对外的表面：
 *   `./markdown/types.js`  —— 共享的形状（`Block` / `Inline` / …）
 *   `./markdown/inline.js` —— 行内解析
 *   `./markdown/block.js`  —— 块级解析（它再调用行内解析）
 */

